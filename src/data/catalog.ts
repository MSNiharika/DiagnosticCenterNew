export function testById(id: string) {
  return tests.find((test) => test.id === id)
}

export function packageById(id: string) {
  return packages.find((item) => item.id === id)
}

export function analytesFor(testIds: string[]): Analyte[] {
  const rows: Analyte[] = []
  const seen = new Set<string>()
  for (const id of testIds) {
    const test = testById(id)
    if (!test) continue
    const panel = PANELS[id]
    if (panel) {
      for (const row of panel) {
        const key = `${row.group}:${row.name}`
        if (seen.has(key)) continue
        seen.add(key)
        rows.push({ ...row, value: "" })
      }
    } else {
      rows.push({
        group: test.department,
        name: test.name,
        value: "",
        unit: "—",
        ref: "Narrative",
      })
    }
  }
  return rows
}

export function packageWorth(item: Package) {
  return item.testIds.reduce((sum, id) => sum + (testById(id)?.price ?? 0), 0)
}
